import json
import os
import re
import sqlite3
import tarfile
import tempfile
from pathlib import Path
from src.config import get_changelog_limit, get_memory_data_dir
from src.db import get_connection, now_iso


def get_export_dir() -> Path:
    """Return the absolute path to the exports directory."""
    return get_memory_data_dir() / "exports"


def get_changelog_dir() -> Path:
    """Return the absolute path to the changelog directory (inside exports/)."""
    return get_export_dir() / "changelog"


def sanitize_filename(scope: str) -> str:
    """
    Sanitize scope names to prevent directory traversal or invalid characters.
    Allows only alphanumeric characters, underscores, and hyphens.
    """
    cleaned = re.sub(r"[^a-zA-Z0-9_-]", "_", scope.strip())
    return cleaned if cleaned else "unnamed_scope"


def atomic_write(target_path: Path, content: str) -> None:
    """
    Atomically write text content using a temporary file and os.replace().
    Guarantees readers never see empty or partially written files.
    """
    target_path.parent.mkdir(parents=True, exist_ok=True)
    temp_file = tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=target_path.parent,
        delete=False,
    )
    try:
        temp_file.write(content)
        temp_file.flush()
        os.fsync(temp_file.fileno())
        temp_file.close()
        os.replace(temp_file.name, target_path)
    except Exception:
        if os.path.exists(temp_file.name):
            os.remove(temp_file.name)
        raise


def sync_markdown_exports() -> list[str]:
    """
    Render all active/stale memories to exports/<scope>.md
    and superseded/archived history to exports/changelog/<scope>_history.md.
    
    Returns a list of all written file paths.
    """
    export_dir = get_export_dir()
    changelog_dir = get_changelog_dir()
    export_dir.mkdir(parents=True, exist_ok=True)
    changelog_dir.mkdir(parents=True, exist_ok=True)
    written_paths: list[str] = []
    expected_active_files: set[Path] = set()
    expected_hist_files: set[Path] = set()

    with get_connection() as conn:
        scopes = [
            r["scope"]
            for r in conn.execute("SELECT DISTINCT scope FROM memories ORDER BY scope").fetchall()
        ]

        for scope in scopes:
            safe_name = sanitize_filename(scope)

            # --- 1. Active & Stale State File ---
            active_rows = conn.execute(
                """
                SELECT id, category, subject, content, status, stale_reason, anchor_files, valid_from
                FROM memories
                WHERE scope = ? AND status IN ('active', 'stale') AND valid_to IS NULL
                ORDER BY
                    CASE category WHEN 'rule' THEN 1 WHEN 'fact' THEN 2 WHEN 'preference' THEN 3 ELSE 4 END,
                    subject,
                    id
                """,
                (scope,),
            ).fetchall()

            scope_file = export_dir / f"{safe_name}.md"
            if active_rows:
                lines = [
                    f"# Memory Scope: `{scope}`",
                    f"_Auto-generated by Helios at {now_iso()}_",
                    "",
                ]
                for r in active_rows:
                    subj = f"**[{r['subject']}]** " if r["subject"] else ""
                    stale_marker = f" `[STALE: {r['stale_reason']}]`" if r["status"] == "stale" else ""
                    anchors = json.loads(r["anchor_files"] or "[]")
                    anchor_marker = f" _(anchors: `{', '.join(anchors)}`)_" if anchors else ""

                    lines.append(
                        f"- `#{r['id']}` ({r['category']}) {subj}{r['content']}{stale_marker}{anchor_marker}"
                    )

                atomic_write(scope_file, "\n".join(lines) + "\n")
                written_paths.append(str(scope_file))
                expected_active_files.add(scope_file)
            elif scope_file.exists():
                scope_file.unlink()

            # --- 2. Historical Changelog Audit Log ---
            changelog_limit = get_changelog_limit()
            history_rows = conn.execute(
                """
                SELECT id, category, subject, content, status, superseded_by, valid_from, valid_to
                FROM memories
                WHERE scope = ? AND status IN ('superseded', 'archived')
                ORDER BY valid_to DESC
                LIMIT ?
                """,
                (scope, changelog_limit),
            ).fetchall()

            hist_file = changelog_dir / f"{safe_name}_history.md"

            if history_rows:
                h_lines = [
                    f"# Changelog Audit: `{scope}`",
                    f"_Tracking superseded and deprecated facts (capped at {changelog_limit})_",
                    "",
                ]
                for h in history_rows:
                    if h["superseded_by"]:
                        action_tag = f"[superseded -> replaced by `#{h['superseded_by']}`]"
                    else:
                        action_tag = "[archived]"

                    subj = f"**[{h['subject']}]** " if h["subject"] else ""
                    h_lines.append(
                        f"- `#{h['id']}` {action_tag} ({h['valid_from']} to {h['valid_to']}): {subj}{h['content']}"
                    )

                atomic_write(hist_file, "\n".join(h_lines) + "\n")
                written_paths.append(str(hist_file))
                expected_hist_files.add(hist_file)
            elif hist_file.exists():
                hist_file.unlink()

    # Clean up orphaned Markdown files from deleted or migrated scopes
    if export_dir.exists():
        for existing_md in export_dir.glob("*.md"):
            if existing_md not in expected_active_files:
                existing_md.unlink(missing_ok=True)

    if changelog_dir.exists():
        for existing_hist in changelog_dir.glob("*.md"):
            if existing_hist not in expected_hist_files:
                existing_hist.unlink(missing_ok=True)

    return written_paths

def create_portable_archive() -> str:
    """
    Produce a portable .tar.gz bundle using SQLite's online backup API.
    Captures WAL state cleanly into a consolidated standalone DB file.
    Packages memory.db and exports/ into helios_portable_bundle.tar.gz atomically.
    """
    sync_markdown_exports()
    data_dir = get_memory_data_dir()
    bundle_path = data_dir / "helios_portable_bundle.tar.gz"

    with tempfile.TemporaryDirectory(dir=data_dir) as tmp_dir:
        temp_snapshot = Path(tmp_dir) / "memory.db"

        # Online SQLite backup: cleanly copies all WAL pages into a consolidated DB file
        with get_connection() as src_conn:
            dest_conn = sqlite3.connect(temp_snapshot)
            try:
                src_conn.backup(dest_conn)
            finally:
                dest_conn.close()

        # Build tar archive containing the snapshot and Markdown files
        temp_tar = Path(tmp_dir) / "temp_bundle.tar.gz"
        with tarfile.open(temp_tar, "w:gz") as tar:
            tar.add(temp_snapshot, arcname="memory.db")
            export_dir = get_export_dir()
            if export_dir.exists():
                tar.add(export_dir, arcname="exports")

        # Atomically move tar archive to final destination
        os.replace(temp_tar, bundle_path)

    return str(bundle_path)